                     + F82 * ( val(k,i+1,j)+val(k,i-2,j) ) &
                     + F83 * ( val(k,i+2,j)+val(k,i-3,j) ) &
                     + F84 * ( val(k,i+3,j)+val(k,i-4,j) ) ) &
                   + GSQRT(k,i,j) * num_diff(k,i,j)
    enddo
    enddo
    enddo
    !$acc end kernels
#ifdef DEBUG
    k = IUNDEF; i = IUNDEF; j = IUNDEF
#endif



    return
  end subroutine ATMOS_DYN_FVM_fluxX_UYZ_cd8

  !-----------------------------------------------------------------------------
