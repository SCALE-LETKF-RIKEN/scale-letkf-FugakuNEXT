  !-----------------------------------------------------------------------------
  !> calculation z-flux at XV
  subroutine ATMOS_DYN_FVM_fluxZ_XVZ_cd8( &
       flux,              &
       mom, val, DENS,    &
       GSQRT, J33G,       &
       num_diff,          &
       CDZ, TwoD,         &
       IIS, IIE, JJS, JJE )
    implicit none

    real(RP), intent(inout) :: flux    (KA,IA,JA)
    real(RP), intent(in)  :: mom     (KA,IA,JA)
    real(RP), intent(in)  :: val     (KA,IA,JA)
    real(RP), intent(in)  :: DENS    (KA,IA,JA)
    real(RP), intent(in)  :: GSQRT   (KA,IA,JA)
    real(RP), intent(in)  :: J33G
    real(RP), intent(in)  :: num_diff(KA,IA,JA)
    real(RP), intent(in)  :: CDZ     (KA)
    logical,  intent(in)  :: TwoD
    integer,  intent(in)  :: IIS, IIE, JJS, JJE

    real(RP) :: vel
    real(RP) :: f2h1_XVZ_k, f2h2_XVZ_k
    real(RP) :: f2h1_XVZ_KS, f2h2_XVZ_KS
    real(RP) :: f2h1_XVZ_KEm1, f2h2_XVZ_KEm1
    real(RP) :: f2h1_XVZ_KSp1, f2h2_XVZ_KSp1
    real(RP) :: f2h1_XVZ_KEm2, f2h2_XVZ_KEm2
    real(RP) :: f2h1_XVZ_KSp2, f2h2_XVZ_KSp2
    real(RP) :: f2h1_XVZ_KEm3, f2h2_XVZ_KEm3
    integer  :: k, i, j
    !---------------------------------------------------------------------------

    !$omp parallel default(none) private(i,j,k,vel) &
    !$omp private(f2h1_XVZ_k,f2h2_XVZ_k,f2h1_XVZ_KS,f2h2_XVZ_KS) &
    !$omp private(f2h1_XVZ_KEm1,f2h2_XVZ_KEm1,f2h1_XVZ_KSp1,f2h2_XVZ_KSp1) &
    !$omp private(f2h1_XVZ_KEm2,f2h2_XVZ_KEm2,f2h1_XVZ_KSp2,f2h2_XVZ_KSp2) &
    !$omp private(f2h1_XVZ_KEm3,f2h2_XVZ_KEm3) &
    !$omp shared(JJS,JJE,IIS,IIE,KS,KE,mom,val,DENS,flux,J33G,GSQRT,num_diff) &
    !$omp shared(CDZ,TwoD)

    !$acc data copy(flux) copyin(mom, val, DENS, GSQRT, num_diff, CDZ)


    !$omp do OMP_SCHEDULE_ collapse(2)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS, IIE
    do k = KS+3, KE-4
#ifdef DEBUG
       call CHECK( __LINE__, mom(k,i,j) )
       call CHECK( __LINE__, mom(k,i,j+1) )

       call CHECK( __LINE__, val(k,i,j) )
       call CHECK( __LINE__, val(k+1,i,j) )

       call CHECK( __LINE__, val(k-1,i,j) )
       call CHECK( __LINE__, val(k+2,i,j) )

       call CHECK( __LINE__, val(k-2,i,j) )
       call CHECK( __LINE__, val(k+3,i,j) )

       call CHECK( __LINE__, val(k-3,i,j) )
       call CHECK( __LINE__, val(k+4,i,j) )

#endif
       f2h1_XVZ_k = F2H(k,I_XVZ)
       f2h2_XVZ_k = 1.0_RP - f2h1_XVZ_k
       vel = ( 0.5_RP * ( mom(k,i,j)+mom(k,i,j+1) ) ) &
           / ( f2h1_XVZ_k * 0.5_RP * ( DENS(k+1,i,j)+DENS(k+1,i,j+1) ) &
             + f2h2_XVZ_k * 0.5_RP * ( DENS(k,i,j)+DENS(k,i,j+1) ) )
       flux(k,i,j) = J33G * vel &
                   * ( F81 * ( val(k+1,i,j)+val(k,i,j) ) &
                     + F82 * ( val(k+2,i,j)+val(k-1,i,j) ) &
                     + F83 * ( val(k+3,i,j)+val(k-2,i,j) ) &
                     + F84 * ( val(k+4,i,j)+val(k-3,i,j) ) ) &
                   + GSQRT(k,i,j) * num_diff(k,i,j)
    enddo
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait
#ifdef DEBUG
    k = IUNDEF; i = IUNDEF; j = IUNDEF
#endif

    !$omp do OMP_SCHEDULE_ collapse(2)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS, IIE
#ifdef DEBUG

       call CHECK( __LINE__, mom(KS,i  ,j) )
       call CHECK( __LINE__, mom(KS,i,j+1) )
       call CHECK( __LINE__, val(KS+1,i,j) )
       call CHECK( __LINE__, val(KS,i,j) )

       call CHECK( __LINE__, mom(KS+1,i  ,j) )
       call CHECK( __LINE__, mom(KS+1,i,j+1) )
       call CHECK( __LINE__, val(KS+3,i,j) )
       call CHECK( __LINE__, val(KS+2,i,j) )

       call CHECK( __LINE__, mom(KS+2,i  ,j) )
       call CHECK( __LINE__, mom(KS+2,i,j+1) )
       call CHECK( __LINE__, val(KS+5,i,j) )
       call CHECK( __LINE__, val(KS+4,i,j) )

#endif
       ! The boundary condition is qflx_hi + qflxJ13 + qfluxJ23 = 0 at KS-1.
       ! The flux at KS-1 can be non-zero.
       ! To reduce calculations, all the fluxes are set to zero.
       flux(KS-1,i,j) = 0.0_RP

       f2h1_XVZ_KS = F2H(KS,I_XVZ)
       f2h2_XVZ_KS = 1.0_RP - f2h1_XVZ_KS
       vel = ( 0.5_RP * ( mom(KS,i,j)+mom(KS,i,j+1) ) ) &
           / ( f2h1_XVZ_KS * 0.5_RP * ( DENS(KS+1,i,j)+DENS(KS+1,i,j+1) ) &
             + f2h2_XVZ_KS * 0.5_RP * ( DENS(KS,i,j)+DENS(KS,i,j+1) ) )
       flux(KS,i,j) = J33G * vel &
                   * ( F2 * ( val(KS+1,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS,i,j) * num_diff(KS,i,j)
       f2h1_XVZ_KEm1 = F2H(KE-1,I_XVZ)
       f2h2_XVZ_KEm1 = 1.0_RP - f2h1_XVZ_KEm1
       vel = ( 0.5_RP * ( mom(KE-1,i,j)+mom(KE-1,i,j+1) ) ) &
           / ( f2h1_XVZ_KEm1 * 0.5_RP * ( DENS(KE,i,j)+DENS(KE,i,j+1) ) &
             + f2h2_XVZ_KEm1 * 0.5_RP * ( DENS(KE-1,i,j)+DENS(KE-1,i,j+1) ) )
       flux(KE-1,i,j) = J33G * vel &
                   * ( F2 * ( val(KE,i,j)+val(KE-1,i,j) ) ) &
                   + GSQRT(KE-1,i,j) * num_diff(KE-1,i,j)

       f2h1_XVZ_KSp1 = F2H(KS+1,I_XVZ)
       f2h2_XVZ_KSp1 = 1.0_RP - f2h1_XVZ_KSp1
       vel = ( 0.5_RP * ( mom(KS+1,i,j)+mom(KS+1,i,j+1) ) ) &
           / ( f2h1_XVZ_KSp1 * 0.5_RP * ( DENS(KS+2,i,j)+DENS(KS+2,i,j+1) ) &
             + f2h2_XVZ_KSp1 * 0.5_RP * ( DENS(KS+1,i,j)+DENS(KS+1,i,j+1) ) )
       flux(KS+1,i,j) = J33G * vel &
                   * ( F41 * ( val(KS+2,i,j)+val(KS+1,i,j) ) &
                     + F42 * ( val(KS+3,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS+1,i,j) * num_diff(KS+1,i,j)
       f2h1_XVZ_KEm2 = F2H(KE-2,I_XVZ)
       f2h2_XVZ_KEm2 = 1.0_RP - f2h1_XVZ_KEm2
       vel = ( 0.5_RP * ( mom(KE-2,i,j)+mom(KE-2,i,j+1) ) ) &
           / ( f2h1_XVZ_KEm2 * 0.5_RP * ( DENS(KE-1,i,j)+DENS(KE-1,i,j+1) ) &
             + f2h2_XVZ_KEm2 * 0.5_RP * ( DENS(KE-2,i,j)+DENS(KE-2,i,j+1) ) )
       flux(KE-2,i,j) = J33G * vel &
                   * ( F41 * ( val(KE-1,i,j)+val(KE-2,i,j) ) &
                     + F42 * ( val(KE,i,j)+val(KE-3,i,j) ) ) &
                   + GSQRT(KE-2,i,j) * num_diff(KE-2,i,j)

       f2h1_XVZ_KSp2 = F2H(KS+2,I_XVZ)
       f2h2_XVZ_KSp2 = 1.0_RP - f2h1_XVZ_KSp2
       vel = ( 0.5_RP * ( mom(KS+2,i,j)+mom(KS+2,i,j+1) ) ) &
           / ( f2h1_XVZ_KSp2 * 0.5_RP * ( DENS(KS+3,i,j)+DENS(KS+3,i,j+1) ) &
             + f2h2_XVZ_KSp2 * 0.5_RP * ( DENS(KS+2,i,j)+DENS(KS+2,i,j+1) ) )
       flux(KS+2,i,j) = J33G * vel &
                   * ( F61 * ( val(KS+3,i,j)+val(KS+2,i,j) ) &
                     + F62 * ( val(KS+4,i,j)+val(KS+1,i,j) ) &
                     + F63 * ( val(KS+5,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS+2,i,j) * num_diff(KS+2,i,j)
       f2h1_XVZ_KEm3 = F2H(KE-3,I_XVZ)
       f2h2_XVZ_KEm3 = 1.0_RP - f2h1_XVZ_KEm3
       vel = ( 0.5_RP * ( mom(KE-3,i,j)+mom(KE-3,i,j+1) ) ) &
           / ( f2h1_XVZ_KEm3 * 0.5_RP * ( DENS(KE-2,i,j)+DENS(KE-2,i,j+1) ) &
             + f2h2_XVZ_KEm3 * 0.5_RP * ( DENS(KE-3,i,j)+DENS(KE-3,i,j+1) ) )
       flux(KE-3,i,j) = J33G * vel &
                   * ( F61 * ( val(KE-2,i,j)+val(KE-3,i,j) ) &
                     + F62 * ( val(KE-1,i,j)+val(KE-4,i,j) ) &
                     + F63 * ( val(KE,i,j)+val(KE-5,i,j) ) ) &
                   + GSQRT(KE-3,i,j) * num_diff(KE-3,i,j)

       flux(KE,i,j) = 0.0_RP
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait


    !$acc end data

    !$omp end parallel
#ifdef DEBUG
    k = IUNDEF; i = IUNDEF; j = IUNDEF
#endif

    return
  end subroutine ATMOS_DYN_FVM_fluxZ_XVZ_cd8

  !-----------------------------------------------------------------------------
  !> calculation J13-flux at XVZ
  subroutine ATMOS_DYN_FVM_fluxJ13_XVZ_cd8( &
       flux,              &
       mom, val, DENS,    &
       GSQRT, J13G, MAPF, &
       CDZ, TwoD,         &
       IIS, IIE, JJS, JJE )
    implicit none

    real(RP), intent(inout) :: flux    (KA,IA,JA)
    real(RP), intent(in)  :: mom     (KA,IA,JA)
    real(RP), intent(in)  :: val     (KA,IA,JA)
    real(RP), intent(in)  :: DENS    (KA,IA,JA)
    real(RP), intent(in)  :: GSQRT   (KA,IA,JA)
    real(RP), intent(in)  :: J13G    (KA,IA,JA)
    real(RP), intent(in)  :: MAPF    (   IA,JA,2)
    real(RP), intent(in)  :: CDZ     (KA)
    logical,  intent(in)  :: TwoD
    integer,  intent(in)  :: IIS, IIE, JJS, JJE

    real(RP) :: vel
    real(RP) :: f2h1_XVZ_k, f2h2_XVZ_k
    real(RP) :: f2h1_XVZ_KS, f2h2_XVZ_KS
    real(RP) :: f2h1_XVZ_KEm1, f2h2_XVZ_KEm1
    real(RP) :: f2h1_XVZ_KSp1, f2h2_XVZ_KSp1
    real(RP) :: f2h1_XVZ_KEm2, f2h2_XVZ_KEm2
    real(RP) :: f2h1_XVZ_KSp2, f2h2_XVZ_KSp2
    real(RP) :: f2h1_XVZ_KEm3, f2h2_XVZ_KEm3
    integer  :: k, i, j
    !---------------------------------------------------------------------------

    !$omp parallel default(none) private(i,j,k,vel) &
    !$omp private(f2h1_XVZ_k,f2h2_XVZ_k,f2h1_XVZ_KS,f2h2_XVZ_KS) &
    !$omp private(f2h1_XVZ_KEm1,f2h2_XVZ_KEm1,f2h1_XVZ_KSp1,f2h2_XVZ_KSp1) &
    !$omp private(f2h1_XVZ_KEm2,f2h2_XVZ_KEm2,f2h1_XVZ_KSp2,f2h2_XVZ_KSp2) &
    !$omp private(f2h1_XVZ_KEm3,f2h2_XVZ_KEm3) &
    !$omp shared(JJS,JJE,IIS,IIE,KS,KE,mom,val,DENS,flux,J13G,MAPF) &
    !$omp shared(GSQRT,CDZ,TwoD)

    !$acc data copy(flux) copyin(mom, val, DENS, GSQRT, J13G, MAPF, CDZ)



    !$omp do OMP_SCHEDULE_ collapse(2)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS, IIE
    do k = KS+3, KE-4
       f2h1_XVZ_k = F2H(k,I_XVZ)
       f2h2_XVZ_k = 1.0_RP - f2h1_XVZ_k
       vel = ( f2h1_XVZ_k * 0.25_RP * ( mom(k+1,i,j)+mom(k+1,i-1,j)+mom(k+1,i,j+1)+mom(k+1,i-1,j+1) ) &
             + f2h2_XVZ_k * 0.25_RP * ( mom(k,i,j)+mom(k,i-1,j)+mom(k,i,j+1)+mom(k,i-1,j+1) ) ) &
           / ( f2h1_XVZ_k * 0.5_RP * ( DENS(k+1,i,j)+DENS(k+1,i,j+1) ) &
             + f2h2_XVZ_k * 0.5_RP * ( DENS(k,i,j)+DENS(k,i,j+1) ) )
       vel = vel * J13G(k,i,j)
       flux(k,i,j) = vel / MAPF(i,j,+2) &
                   * ( F81 * ( val(k+1,i,j)+val(k,i,j) ) &
                     + F82 * ( val(k+2,i,j)+val(k-1,i,j) ) &
                     + F83 * ( val(k+3,i,j)+val(k-2,i,j) ) &
                     + F84 * ( val(k+4,i,j)+val(k-3,i,j) ) )
    enddo
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait

    !$omp do OMP_SCHEDULE_ collapse(2)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS, IIE
       ! The boundary condition is qflx_hi + qflxJ13 + qfluxJ23 = 0 at KS-1.
       ! The flux at KS-1 can be non-zero.
       ! To reduce calculations, all the fluxes are set to zero.
       flux(KS-1,i,j) = 0.0_RP

       f2h1_XVZ_KS = F2H(KS,I_XVZ)
       f2h2_XVZ_KS = 1.0_RP - f2h1_XVZ_KS
       vel = ( f2h1_XVZ_KS * 0.25_RP * ( mom(KS+1,i,j)+mom(KS+1,i-1,j)+mom(KS+1,i,j+1)+mom(KS+1,i-1,j+1) ) &
             + f2h2_XVZ_KS * 0.25_RP * ( mom(KS,i,j)+mom(KS,i-1,j)+mom(KS,i,j+1)+mom(KS,i-1,j+1) ) ) &
           / ( f2h1_XVZ_KS * 0.5_RP * ( DENS(KS+1,i,j)+DENS(KS+1,i,j+1) ) &
             + f2h2_XVZ_KS * 0.5_RP * ( DENS(KS,i,j)+DENS(KS,i,j+1) ) )
       vel = vel * J13G(KS,i,j)
       flux(KS,i,j) = vel / MAPF(i,j,+2) &
                   * ( F2 * ( val(KS+1,i,j)+val(KS,i,j) ) )

       f2h1_XVZ_KEm1 = F2H(KE-1,I_XVZ)
       f2h2_XVZ_KEm1 = 1.0_RP - f2h1_XVZ_KEm1
       vel = ( f2h1_XVZ_KEm1 * 0.25_RP * ( mom(KE,i,j)+mom(KE,i-1,j)+mom(KE,i,j+1)+mom(KE,i-1,j+1) ) &
             + f2h2_XVZ_KEm1 * 0.25_RP * ( mom(KE-1,i,j)+mom(KE-1,i-1,j)+mom(KE-1,i,j+1)+mom(KE-1,i-1,j+1) ) ) &
           / ( f2h1_XVZ_KEm1 * 0.5_RP * ( DENS(KE,i,j)+DENS(KE,i,j+1) ) &
             + f2h2_XVZ_KEm1 * 0.5_RP * ( DENS(KE-1,i,j)+DENS(KE-1,i,j+1) ) )
       vel = vel * J13G(KE-1,i,j)
       flux(KE-1,i,j) = vel / MAPF(i,j,+2) &
                   * ( F2 * ( val(KE,i,j)+val(KE-1,i,j) ) )

       f2h1_XVZ_KSp1 = F2H(KS+1,I_XVZ)
       f2h2_XVZ_KSp1 = 1.0_RP - f2h1_XVZ_KSp1
       vel = ( f2h1_XVZ_KSp1 * 0.25_RP * ( mom(KS+2,i,j)+mom(KS+2,i-1,j)+mom(KS+2,i,j+1)+mom(KS+2,i-1,j+1) ) &
             + f2h2_XVZ_KSp1 * 0.25_RP * ( mom(KS+1,i,j)+mom(KS+1,i-1,j)+mom(KS+1,i,j+1)+mom(KS+1,i-1,j+1) ) ) &
           / ( f2h1_XVZ_KSp1 * 0.5_RP * ( DENS(KS+2,i,j)+DENS(KS+2,i,j+1) ) &
             + f2h2_XVZ_KSp1 * 0.5_RP * ( DENS(KS+1,i,j)+DENS(KS+1,i,j+1) ) )
       vel = vel * J13G(KS+1,i,j)
       flux(KS+1,i,j) = vel / MAPF(i,j,+2) &
                   * ( F41 * ( val(KS+2,i,j)+val(KS+1,i,j) ) &
                     + F42 * ( val(KS+3,i,j)+val(KS,i,j) ) )

       f2h1_XVZ_KEm2 = F2H(KE-2,I_XVZ)
       f2h2_XVZ_KEm2 = 1.0_RP - f2h1_XVZ_KEm2
       vel = ( f2h1_XVZ_KEm2 * 0.25_RP * ( mom(KE-1,i,j)+mom(KE-1,i-1,j)+mom(KE-1,i,j+1)+mom(KE-1,i-1,j+1) ) &
             + f2h2_XVZ_KEm2 * 0.25_RP * ( mom(KE-2,i,j)+mom(KE-2,i-1,j)+mom(KE-2,i,j+1)+mom(KE-2,i-1,j+1) ) ) &
           / ( f2h1_XVZ_KEm2 * 0.5_RP * ( DENS(KE-1,i,j)+DENS(KE-1,i,j+1) ) &
             + f2h2_XVZ_KEm2 * 0.5_RP * ( DENS(KE-2,i,j)+DENS(KE-2,i,j+1) ) )
       vel = vel * J13G(KE-2,i,j)
       flux(KE-2,i,j) = vel / MAPF(i,j,+2) &
                   * ( F41 * ( val(KE-1,i,j)+val(KE-2,i,j) ) &
                     + F42 * ( val(KE,i,j)+val(KE-3,i,j) ) )

       f2h1_XVZ_KSp2 = F2H(KS+2,I_XVZ)
       f2h2_XVZ_KSp2 = 1.0_RP - f2h1_XVZ_KSp2
       vel = ( f2h1_XVZ_KSp2 * 0.25_RP * ( mom(KS+3,i,j)+mom(KS+3,i-1,j)+mom(KS+3,i,j+1)+mom(KS+3,i-1,j+1) ) &
             + f2h2_XVZ_KSp2 * 0.25_RP * ( mom(KS+2,i,j)+mom(KS+2,i-1,j)+mom(KS+2,i,j+1)+mom(KS+2,i-1,j+1) ) ) &
           / ( f2h1_XVZ_KSp2 * 0.5_RP * ( DENS(KS+3,i,j)+DENS(KS+3,i,j+1) ) &
             + f2h2_XVZ_KSp2 * 0.5_RP * ( DENS(KS+2,i,j)+DENS(KS+2,i,j+1) ) )
       vel = vel * J13G(KS+2,i,j)
       flux(KS+2,i,j) = vel / MAPF(i,j,+2) &
                   * ( F61 * ( val(KS+3,i,j)+val(KS+2,i,j) ) &
                     + F62 * ( val(KS+4,i,j)+val(KS+1,i,j) ) &
                     + F63 * ( val(KS+5,i,j)+val(KS,i,j) ) )

       f2h1_XVZ_KEm3 = F2H(KE-3,I_XVZ)
       f2h2_XVZ_KEm3 = 1.0_RP - f2h1_XVZ_KEm3
       vel = ( f2h1_XVZ_KEm3 * 0.25_RP * ( mom(KE-2,i,j)+mom(KE-2,i-1,j)+mom(KE-2,i,j+1)+mom(KE-2,i-1,j+1) ) &
             + f2h2_XVZ_KEm3 * 0.25_RP * ( mom(KE-3,i,j)+mom(KE-3,i-1,j)+mom(KE-3,i,j+1)+mom(KE-3,i-1,j+1) ) ) &
           / ( f2h1_XVZ_KEm3 * 0.5_RP * ( DENS(KE-2,i,j)+DENS(KE-2,i,j+1) ) &
             + f2h2_XVZ_KEm3 * 0.5_RP * ( DENS(KE-3,i,j)+DENS(KE-3,i,j+1) ) )
       vel = vel * J13G(KE-3,i,j)
       flux(KE-3,i,j) = vel / MAPF(i,j,+2) &
                   * ( F61 * ( val(KE-2,i,j)+val(KE-3,i,j) ) &
                     + F62 * ( val(KE-1,i,j)+val(KE-4,i,j) ) &
                     + F63 * ( val(KE,i,j)+val(KE-5,i,j) ) )

       flux(KE  ,i,j) = 0.0_RP
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait



    !$acc end data

    !$omp end parallel
    return
  end subroutine ATMOS_DYN_FVM_fluxJ13_XVZ_cd8

  !-----------------------------------------------------------------------------
  !> calculation J23-flux at XVZ
  subroutine ATMOS_DYN_FVM_fluxJ23_XVZ_cd8( &
       flux,              &
       mom, val, DENS,    &
       GSQRT, J23G, MAPF, &
       CDZ, TwoD,         &
       IIS, IIE, JJS, JJE )
    implicit none

    real(RP), intent(inout) :: flux    (KA,IA,JA)
    real(RP), intent(in)  :: mom     (KA,IA,JA)
    real(RP), intent(in)  :: val     (KA,IA,JA)
    real(RP), intent(in)  :: DENS    (KA,IA,JA)
    real(RP), intent(in)  :: GSQRT   (KA,IA,JA)
    real(RP), intent(in)  :: J23G    (KA,IA,JA)
    real(RP), intent(in)  :: MAPF    (   IA,JA,2)
    real(RP), intent(in)  :: CDZ     (KA)
    logical,  intent(in)  :: TwoD
    integer,  intent(in)  :: IIS, IIE, JJS, JJE

    real(RP) :: vel
    real(RP) :: f2h1_XVZ_k, f2h2_XVZ_k
    real(RP) :: f2h1_XVZ_KS, f2h2_XVZ_KS
    real(RP) :: f2h1_XVZ_KEm1, f2h2_XVZ_KEm1
    real(RP) :: f2h1_XVZ_KSp1, f2h2_XVZ_KSp1
    real(RP) :: f2h1_XVZ_KEm2, f2h2_XVZ_KEm2
    real(RP) :: f2h1_XVZ_KSp2, f2h2_XVZ_KSp2
    real(RP) :: f2h1_XVZ_KEm3, f2h2_XVZ_KEm3
    integer  :: k, i, j
    !---------------------------------------------------------------------------

    !$omp parallel default(none) private(i,j,k,vel) &
    !$omp private(f2h1_XVZ_k,f2h2_XVZ_k,f2h1_XVZ_KS,f2h2_XVZ_KS) &
    !$omp private(f2h1_XVZ_KEm1,f2h2_XVZ_KEm1,f2h1_XVZ_KSp1,f2h2_XVZ_KSp1) &
    !$omp private(f2h1_XVZ_KEm2,f2h2_XVZ_KEm2,f2h1_XVZ_KSp2,f2h2_XVZ_KSp2) &
    !$omp private(f2h1_XVZ_KEm3,f2h2_XVZ_KEm3) &
    !$omp shared(JJS,JJE,IIS,IIE,KS,KE,mom,val,DENS,flux,J23G,MAPF) &
    !$omp shared(GSQRT,CDZ,TwoD)

    !$acc data copy(flux) copyin(mom, val, DENS, GSQRT, J23G, MAPF, CDZ)



    !$omp do OMP_SCHEDULE_ collapse(2)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS, IIE
    do k = KS+3, KE-4
       f2h1_XVZ_k = F2H(k,I_XVZ)
       f2h2_XVZ_k = 1.0_RP - f2h1_XVZ_k
       vel = ( f2h1_XVZ_k * mom(k+1,i,j) &
             + f2h2_XVZ_k * mom(k,i,j) ) &
           / ( f2h1_XVZ_k * 0.5_RP * ( DENS(k+1,i,j)+DENS(k+1,i,j+1) ) &
             + f2h2_XVZ_k * 0.5_RP * ( DENS(k,i,j)+DENS(k,i,j+1) ) )
       vel = vel * J23G(k,i,j)
       flux(k,i,j) = vel / MAPF(i,j,+1) &
                   * ( F81 * ( val(k+1,i,j)+val(k,i,j) ) &
                     + F82 * ( val(k+2,i,j)+val(k-1,i,j) ) &
                     + F83 * ( val(k+3,i,j)+val(k-2,i,j) ) &
                     + F84 * ( val(k+4,i,j)+val(k-3,i,j) ) )
    enddo
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait

    !$omp do OMP_SCHEDULE_ collapse(2)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS, IIE
       ! The boundary condition is qflx_hi + qflxJ13 + qfluxJ23 = 0 at KS-1.
       ! The flux at KS-1 can be non-zero.
       ! To reduce calculations, all the fluxes are set to zero.
       flux(KS-1,i,j) = 0.0_RP

       f2h1_XVZ_KS = F2H(KS,I_XVZ)
       f2h2_XVZ_KS = 1.0_RP - f2h1_XVZ_KS
       vel = ( f2h1_XVZ_KS * mom(KS+1,i,j) &
             + f2h2_XVZ_KS * mom(KS,i,j) ) &
           / ( f2h1_XVZ_KS * 0.5_RP * ( DENS(KS+1,i,j)+DENS(KS+1,i,j+1) ) &
             + f2h2_XVZ_KS * 0.5_RP * ( DENS(KS,i,j)+DENS(KS,i,j+1) ) )
       vel = vel * J23G(KS,i,j)
       flux(KS,i,j) = vel / MAPF(i,j,+1) &
                   * ( F2 * ( val(KS+1,i,j)+val(KS,i,j) ) )

       f2h1_XVZ_KEm1 = F2H(KE-1,I_XVZ)
       f2h2_XVZ_KEm1 = 1.0_RP - f2h1_XVZ_KEm1
       vel = ( f2h1_XVZ_KEm1 * mom(KE,i,j) &
             + f2h2_XVZ_KEm1 * mom(KE-1,i,j) ) &
           / ( f2h1_XVZ_KEm1 * 0.5_RP * ( DENS(KE,i,j)+DENS(KE,i,j+1) ) &
             + f2h2_XVZ_KEm1 * 0.5_RP * ( DENS(KE-1,i,j)+DENS(KE-1,i,j+1) ) )
       vel = vel * J23G(KE-1,i,j)
       flux(KE-1,i,j) = vel / MAPF(i,j,+1) &
                   * ( F2 * ( val(KE,i,j)+val(KE-1,i,j) ) )

       f2h1_XVZ_KSp1 = F2H(KS+1,I_XVZ)
       f2h2_XVZ_KSp1 = 1.0_RP - f2h1_XVZ_KSp1
       vel = ( f2h1_XVZ_KSp1 * mom(KS+2,i,j) &
             + f2h2_XVZ_KSp1 * mom(KS+1,i,j) ) &
           / ( f2h1_XVZ_KSp1 * 0.5_RP * ( DENS(KS+2,i,j)+DENS(KS+2,i,j+1) ) &
             + f2h2_XVZ_KSp1 * 0.5_RP * ( DENS(KS+1,i,j)+DENS(KS+1,i,j+1) ) )
       vel = vel * J23G(KS+1,i,j)
       flux(KS+1,i,j) = vel / MAPF(i,j,+1) &
                   * ( F41 * ( val(KS+2,i,j)+val(KS+1,i,j) ) &
                     + F42 * ( val(KS+3,i,j)+val(KS,i,j) ) )

       f2h1_XVZ_KEm2 = F2H(KE-2,I_XVZ)
       f2h2_XVZ_KEm2 = 1.0_RP - f2h1_XVZ_KEm2
       vel = ( f2h1_XVZ_KEm2 * mom(KE-1,i,j) &
             + f2h2_XVZ_KEm2 * mom(KE-2,i,j) ) &
           / ( f2h1_XVZ_KEm2 * 0.5_RP * ( DENS(KE-1,i,j)+DENS(KE-1,i,j+1) ) &
             + f2h2_XVZ_KEm2 * 0.5_RP * ( DENS(KE-2,i,j)+DENS(KE-2,i,j+1) ) )
       vel = vel * J23G(KE-2,i,j)
       flux(KE-2,i,j) = vel / MAPF(i,j,+1) &
                   * ( F41 * ( val(KE-1,i,j)+val(KE-2,i,j) ) &
                     + F42 * ( val(KE,i,j)+val(KE-3,i,j) ) )

       f2h1_XVZ_KSp2 = F2H(KS+2,I_XVZ)
       f2h2_XVZ_KSp2 = 1.0_RP - f2h1_XVZ_KSp2
       vel = ( f2h1_XVZ_KSp2 * mom(KS+3,i,j) &
             + f2h2_XVZ_KSp2 * mom(KS+2,i,j) ) &
           / ( f2h1_XVZ_KSp2 * 0.5_RP * ( DENS(KS+3,i,j)+DENS(KS+3,i,j+1) ) &
             + f2h2_XVZ_KSp2 * 0.5_RP * ( DENS(KS+2,i,j)+DENS(KS+2,i,j+1) ) )
       vel = vel * J23G(KS+2,i,j)
       flux(KS+2,i,j) = vel / MAPF(i,j,+1) &
                   * ( F61 * ( val(KS+3,i,j)+val(KS+2,i,j) ) &
                     + F62 * ( val(KS+4,i,j)+val(KS+1,i,j) ) &
                     + F63 * ( val(KS+5,i,j)+val(KS,i,j) ) )

       f2h1_XVZ_KEm3 = F2H(KE-3,I_XVZ)
       f2h2_XVZ_KEm3 = 1.0_RP - f2h1_XVZ_KEm3
       vel = ( f2h1_XVZ_KEm3 * mom(KE-2,i,j) &
             + f2h2_XVZ_KEm3 * mom(KE-3,i,j) ) &
           / ( f2h1_XVZ_KEm3 * 0.5_RP * ( DENS(KE-2,i,j)+DENS(KE-2,i,j+1) ) &
             + f2h2_XVZ_KEm3 * 0.5_RP * ( DENS(KE-3,i,j)+DENS(KE-3,i,j+1) ) )
       vel = vel * J23G(KE-3,i,j)
       flux(KE-3,i,j) = vel / MAPF(i,j,+1) &
                   * ( F61 * ( val(KE-2,i,j)+val(KE-3,i,j) ) &
                     + F62 * ( val(KE-1,i,j)+val(KE-4,i,j) ) &
                     + F63 * ( val(KE,i,j)+val(KE-5,i,j) ) )

       flux(KE  ,i,j) = 0.0_RP
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait



    !$acc end data

    !$omp end parallel
    return
  end subroutine ATMOS_DYN_FVM_fluxJ23_XVZ_cd8

  !-----------------------------------------------------------------------------
  !> calculation X-flux at XV
  subroutine ATMOS_DYN_FVM_fluxX_XVZ_cd8( &
       flux,              &
       mom, val, DENS,    &
       GSQRT, MAPF,       &
       num_diff,          &
       CDZ, TwoD,         &
       IIS, IIE, JJS, JJE )
    implicit none

    real(RP), intent(inout) :: flux    (KA,IA,JA)
    real(RP), intent(in)  :: mom     (KA,IA,JA)
    real(RP), intent(in)  :: val     (KA,IA,JA)
    real(RP), intent(in)  :: DENS    (KA,IA,JA)
    real(RP), intent(in)  :: GSQRT   (KA,IA,JA)
    real(RP), intent(in)  :: MAPF    (   IA,JA,2)
    real(RP), intent(in)  :: num_diff(KA,IA,JA)
    real(RP), intent(in)  :: CDZ     (KA)
    logical,  intent(in)  :: TwoD
    integer,  intent(in)  :: IIS, IIE, JJS, JJE

    real(RP) :: vel
    integer  :: k, i, j
    !---------------------------------------------------------------------------



    !$omp parallel do default(none) private(i,j,k) OMP_SCHEDULE_ collapse(2) &
    !$omp private(vel) &
    !$omp shared(JJS,JJE,IIS,IIE,KS,KE,mom,val,DENS,flux,GSQRT,MAPF,num_diff)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS-1, IIE
    do k = KS, KE
#ifdef DEBUG
       call CHECK( __LINE__, mom(k,i  ,j) )
       call CHECK( __LINE__, mom(k,i,j-1) )

       call CHECK( __LINE__, val(k,i,j) )
       call CHECK( __LINE__, val(k,i+1,j) )

       call CHECK( __LINE__, val(k,i-1,j) )
       call CHECK( __LINE__, val(k,i+2,j) )

       call CHECK( __LINE__, val(k,i-2,j) )
       call CHECK( __LINE__, val(k,i+3,j) )

       call CHECK( __LINE__, val(k,i-3,j) )
       call CHECK( __LINE__, val(k,i+4,j) )

#endif
       vel = ( 0.5_RP * ( mom(k,i,j)+mom(k,i,j+1) ) ) &
           / ( 0.25_RP * ( DENS(k,i,j)+DENS(k,i+1,j)+DENS(k,i,j+1)+DENS(k,i+1,j+1) ) )
       flux(k,i,j) = GSQRT(k,i,j) / MAPF(i,j,+2) * vel &
                   * ( F81 * ( val(k,i+1,j)+val(k,i,j) ) &
                     + F82 * ( val(k,i+2,j)+val(k,i-1,j) ) &
                     + F83 * ( val(k,i+3,j)+val(k,i-2,j) ) &
                     + F84 * ( val(k,i+4,j)+val(k,i-3,j) ) ) &
                   + GSQRT(k,i,j) * num_diff(k,i,j)
    enddo
    enddo
    enddo
    !$acc end kernels
#ifdef DEBUG
    k = IUNDEF; i = IUNDEF; j = IUNDEF
#endif



    return
  end subroutine ATMOS_DYN_FVM_fluxX_XVZ_cd8

  !-----------------------------------------------------------------------------
  !> calculation Y-flux at XV
  subroutine ATMOS_DYN_FVM_fluxY_XVZ_cd8( &
       flux,              &
       mom, val, DENS,    &
       GSQRT, MAPF,       &
       num_diff,          &
       CDZ, TwoD,         &
       IIS, IIE, JJS, JJE )
    implicit none

    real(RP), intent(inout) :: flux    (KA,IA,JA)
    real(RP), intent(in)  :: mom     (KA,IA,JA)
    real(RP), intent(in)  :: val     (KA,IA,JA)
    real(RP), intent(in)  :: DENS    (KA,IA,JA)
    real(RP), intent(in)  :: GSQRT   (KA,IA,JA)
    real(RP), intent(in)  :: MAPF    (   IA,JA,2)
    real(RP), intent(in)  :: num_diff(KA,IA,JA)
    real(RP), intent(in)  :: CDZ     (KA)
    logical,  intent(in)  :: TwoD
    integer,  intent(in)  :: IIS, IIE, JJS, JJE

    real(RP) :: vel
    integer  :: k, i, j
    !---------------------------------------------------------------------------

    ! note that y-index is added by -1



    !$omp parallel do default(none) private(i,j,k) OMP_SCHEDULE_ collapse(2) &
    !$omp private(vel) &
    !$omp shared(JJS,JJE,IIS,IIE,KS,KE,mom,val,DENS,flux,GSQRT,MAPF,num_diff)
    !$acc kernels
    do j = JJS, JJE+1
    do i = IIS, IIE
    do k = KS, KE
#ifdef DEBUG
       call CHECK( __LINE__, mom(k,i  ,j) )
       call CHECK( __LINE__, mom(k,i,j-1) )

       call CHECK( __LINE__, val(k,i,j-1) )
       call CHECK( __LINE__, val(k,i,j) )

       call CHECK( __LINE__, val(k,i,j-2) )
       call CHECK( __LINE__, val(k,i,j+1) )

       call CHECK( __LINE__, val(k,i,j-3) )
       call CHECK( __LINE__, val(k,i,j+2) )

       call CHECK( __LINE__, val(k,i,j-4) )
       call CHECK( __LINE__, val(k,i,j+3) )

#endif
       vel = ( 0.5_RP * ( mom(k,i,j)+mom(k,i,j-1) ) ) &
           / ( DENS(k,i,j) )
       flux(k,i,j-1) = GSQRT(k,i,j) / MAPF(i,j,+1) * vel &
                   * ( F81 * ( val(k,i,j)+val(k,i,j-1) ) &
                     + F82 * ( val(k,i,j+1)+val(k,i,j-2) ) &
                     + F83 * ( val(k,i,j+2)+val(k,i,j-3) ) &
                     + F84 * ( val(k,i,j+3)+val(k,i,j-4) ) ) &
                   + GSQRT(k,i,j) * num_diff(k,i,j)
    enddo
    enddo
    enddo
    !$acc end kernels
#ifdef DEBUG
    k = IUNDEF; i = IUNDEF; j = IUNDEF
#endif



    return
  end subroutine ATMOS_DYN_FVM_fluxY_XVZ_cd8







