       vel = ( mom(k,i,j) ) &
           / ( f2h1_XYZ_k * DENS(k+1,i,j) &
             + f2h2_XYZ_k * DENS(k,i,j) )
       flux(k,i,j) = J33G * vel &
                   * ( F81 * ( val(k+1,i,j)+val(k,i,j) ) &
                     + F82 * ( val(k+2,i,j)+val(k-1,i,j) ) &
                     + F83 * ( val(k+3,i,j)+val(k-2,i,j) ) &
                     + F84 * ( val(k+4,i,j)+val(k-3,i,j) ) ) &
                   + GSQRT(k,i,j) * num_diff(k,i,j)
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait
#ifdef DEBUG
    k = IUNDEF; i = IUNDEF; j = IUNDEF
#endif

    !$omp do OMP_SCHEDULE_
    !$acc kernels
    do j = JJS, JJE
       i = IIS
#ifdef DEBUG

       call CHECK( __LINE__, mom(KS,i  ,j) )
       call CHECK( __LINE__, val(KS+1,i,j) )
       call CHECK( __LINE__, val(KS,i,j) )

       call CHECK( __LINE__, mom(KS+1,i  ,j) )
       call CHECK( __LINE__, val(KS+3,i,j) )
       call CHECK( __LINE__, val(KS+2,i,j) )

       call CHECK( __LINE__, mom(KS+2,i  ,j) )
       call CHECK( __LINE__, val(KS+5,i,j) )
       call CHECK( __LINE__, val(KS+4,i,j) )

#endif
       ! The boundary condition is qflx_hi + qflxJ13 + qfluxJ23 = 0 at KS-1.
       ! The flux at KS-1 can be non-zero.
       ! To reduce calculations, all the fluxes are set to zero.
       flux(KS-1,i,j) = 0.0_RP

       f2h1_XYZ_KS = F2H(KS,I_XYZ)
       f2h2_XYZ_KS = 1.0_RP - f2h1_XYZ_KS
       vel = ( mom(KS,i,j) ) &
           / ( f2h1_XYZ_KS * DENS(KS+1,i,j) &
             + f2h2_XYZ_KS * DENS(KS,i,j) )
       flux(KS,i,j) = J33G * vel &
                   * ( F2 * ( val(KS+1,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS,i,j) * num_diff(KS,i,j)
       f2h1_XYZ_KEm1 = F2H(KE-1,I_XYZ)
       f2h2_XYZ_KEm1 = 1.0_RP - f2h1_XYZ_KEm1
       vel = ( mom(KE-1,i,j) ) &
           / ( f2h1_XYZ_KEm1 * DENS(KE,i,j) &
             + f2h2_XYZ_KEm1 * DENS(KE-1,i,j) )
       flux(KE-1,i,j) = J33G * vel &
                   * ( F2 * ( val(KE,i,j)+val(KE-1,i,j) ) ) &
                   + GSQRT(KE-1,i,j) * num_diff(KE-1,i,j)

       f2h1_XYZ_KSp1 = F2H(KS+1,I_XYZ)
       f2h2_XYZ_KSp1 = 1.0_RP - f2h1_XYZ_KSp1
       vel = ( mom(KS+1,i,j) ) &
           / ( f2h1_XYZ_KSp1 * DENS(KS+2,i,j) &
             + f2h2_XYZ_KSp1 * DENS(KS+1,i,j) )
       flux(KS+1,i,j) = J33G * vel &
                   * ( F41 * ( val(KS+2,i,j)+val(KS+1,i,j) ) &
                     + F42 * ( val(KS+3,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS+1,i,j) * num_diff(KS+1,i,j)
       f2h1_XYZ_KEm2 = F2H(KE-2,I_XYZ)
       f2h2_XYZ_KEm2 = 1.0_RP - f2h1_XYZ_KEm2
       vel = ( mom(KE-2,i,j) ) &
           / ( f2h1_XYZ_KEm2 * DENS(KE-1,i,j) &
             + f2h2_XYZ_KEm2 * DENS(KE-2,i,j) )
       flux(KE-2,i,j) = J33G * vel &
                   * ( F41 * ( val(KE-1,i,j)+val(KE-2,i,j) ) &
                     + F42 * ( val(KE,i,j)+val(KE-3,i,j) ) ) &
                   + GSQRT(KE-2,i,j) * num_diff(KE-2,i,j)

       f2h1_XYZ_KSp2 = F2H(KS+2,I_XYZ)
       f2h2_XYZ_KSp2 = 1.0_RP - f2h1_XYZ_KSp2
       vel = ( mom(KS+2,i,j) ) &
           / ( f2h1_XYZ_KSp2 * DENS(KS+3,i,j) &
             + f2h2_XYZ_KSp2 * DENS(KS+2,i,j) )
       flux(KS+2,i,j) = J33G * vel &
                   * ( F61 * ( val(KS+3,i,j)+val(KS+2,i,j) ) &
                     + F62 * ( val(KS+4,i,j)+val(KS+1,i,j) ) &
                     + F63 * ( val(KS+5,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS+2,i,j) * num_diff(KS+2,i,j)
       f2h1_XYZ_KEm3 = F2H(KE-3,I_XYZ)
       f2h2_XYZ_KEm3 = 1.0_RP - f2h1_XYZ_KEm3
       vel = ( mom(KE-3,i,j) ) &
           / ( f2h1_XYZ_KEm3 * DENS(KE-2,i,j) &
             + f2h2_XYZ_KEm3 * DENS(KE-3,i,j) )
       flux(KE-3,i,j) = J33G * vel &
                   * ( F61 * ( val(KE-2,i,j)+val(KE-3,i,j) ) &
                     + F62 * ( val(KE-1,i,j)+val(KE-4,i,j) ) &
                     + F63 * ( val(KE,i,j)+val(KE-5,i,j) ) ) &
                   + GSQRT(KE-3,i,j) * num_diff(KE-3,i,j)

       flux(KE,i,j) = 0.0_RP
    enddo
    !$acc end kernels
    !$omp end do nowait

    else


    !$omp do OMP_SCHEDULE_ collapse(2)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS, IIE
    do k = KS+3, KE-4
#ifdef DEBUG
       call CHECK( __LINE__, mom(k,i,j) )
       call CHECK( __LINE__, mom(k,i+1,j) )

       call CHECK( __LINE__, val(k,i,j) )
       call CHECK( __LINE__, val(k+1,i,j) )

       call CHECK( __LINE__, val(k-1,i,j) )
       call CHECK( __LINE__, val(k+2,i,j) )

       call CHECK( __LINE__, val(k-2,i,j) )
       call CHECK( __LINE__, val(k+3,i,j) )

       call CHECK( __LINE__, val(k-3,i,j) )
       call CHECK( __LINE__, val(k+4,i,j) )

#endif
       f2h1_UYZ_k = F2H(k,I_UYZ)
       f2h2_UYZ_k = 1.0_RP - f2h1_UYZ_k
       vel = ( 0.5_RP * ( mom(k,i,j)+mom(k,i+1,j) ) ) &
           / ( f2h1_UYZ_k * 0.5_RP * ( DENS(k+1,i,j)+DENS(k+1,i+1,j) ) &
             + f2h2_UYZ_k * 0.5_RP * ( DENS(k,i,j)+DENS(k,i+1,j) ) )
       flux(k,i,j) = J33G * vel &
                   * ( F81 * ( val(k+1,i,j)+val(k,i,j) ) &
                     + F82 * ( val(k+2,i,j)+val(k-1,i,j) ) &
                     + F83 * ( val(k+3,i,j)+val(k-2,i,j) ) &
                     + F84 * ( val(k+4,i,j)+val(k-3,i,j) ) ) &
                   + GSQRT(k,i,j) * num_diff(k,i,j)
    enddo
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait
#ifdef DEBUG
    k = IUNDEF; i = IUNDEF; j = IUNDEF
#endif

    !$omp do OMP_SCHEDULE_ collapse(2)
    !$acc kernels
    do j = JJS, JJE
    do i = IIS, IIE
#ifdef DEBUG

       call CHECK( __LINE__, mom(KS,i  ,j) )
       call CHECK( __LINE__, mom(KS,i+1,j) )
       call CHECK( __LINE__, val(KS+1,i,j) )
       call CHECK( __LINE__, val(KS,i,j) )

       call CHECK( __LINE__, mom(KS+1,i  ,j) )
       call CHECK( __LINE__, mom(KS+1,i+1,j) )
       call CHECK( __LINE__, val(KS+3,i,j) )
       call CHECK( __LINE__, val(KS+2,i,j) )

       call CHECK( __LINE__, mom(KS+2,i  ,j) )
       call CHECK( __LINE__, mom(KS+2,i+1,j) )
       call CHECK( __LINE__, val(KS+5,i,j) )
       call CHECK( __LINE__, val(KS+4,i,j) )

#endif
       ! The boundary condition is qflx_hi + qflxJ13 + qfluxJ23 = 0 at KS-1.
       ! The flux at KS-1 can be non-zero.
       ! To reduce calculations, all the fluxes are set to zero.
       flux(KS-1,i,j) = 0.0_RP

       f2h1_UYZ_KS = F2H(KS,I_UYZ)
       f2h2_UYZ_KS = 1.0_RP - f2h1_UYZ_KS
       vel = ( 0.5_RP * ( mom(KS,i,j)+mom(KS,i+1,j) ) ) &
           / ( f2h1_UYZ_KS * 0.5_RP * ( DENS(KS+1,i,j)+DENS(KS+1,i+1,j) ) &
             + f2h2_UYZ_KS * 0.5_RP * ( DENS(KS,i,j)+DENS(KS,i+1,j) ) )
       flux(KS,i,j) = J33G * vel &
                   * ( F2 * ( val(KS+1,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS,i,j) * num_diff(KS,i,j)
       f2h1_UYZ_KEm1 = F2H(KE-1,I_UYZ)
       f2h2_UYZ_KEm1 = 1.0_RP - f2h1_UYZ_KEm1
       vel = ( 0.5_RP * ( mom(KE-1,i,j)+mom(KE-1,i+1,j) ) ) &
           / ( f2h1_UYZ_KEm1 * 0.5_RP * ( DENS(KE,i,j)+DENS(KE,i+1,j) ) &
             + f2h2_UYZ_KEm1 * 0.5_RP * ( DENS(KE-1,i,j)+DENS(KE-1,i+1,j) ) )
       flux(KE-1,i,j) = J33G * vel &
                   * ( F2 * ( val(KE,i,j)+val(KE-1,i,j) ) ) &
                   + GSQRT(KE-1,i,j) * num_diff(KE-1,i,j)

       f2h1_UYZ_KSp1 = F2H(KS+1,I_UYZ)
       f2h2_UYZ_KSp1 = 1.0_RP - f2h1_UYZ_KSp1
       vel = ( 0.5_RP * ( mom(KS+1,i,j)+mom(KS+1,i+1,j) ) ) &
           / ( f2h1_UYZ_KSp1 * 0.5_RP * ( DENS(KS+2,i,j)+DENS(KS+2,i+1,j) ) &
             + f2h2_UYZ_KSp1 * 0.5_RP * ( DENS(KS+1,i,j)+DENS(KS+1,i+1,j) ) )
       flux(KS+1,i,j) = J33G * vel &
                   * ( F41 * ( val(KS+2,i,j)+val(KS+1,i,j) ) &
                     + F42 * ( val(KS+3,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS+1,i,j) * num_diff(KS+1,i,j)
       f2h1_UYZ_KEm2 = F2H(KE-2,I_UYZ)
       f2h2_UYZ_KEm2 = 1.0_RP - f2h1_UYZ_KEm2
       vel = ( 0.5_RP * ( mom(KE-2,i,j)+mom(KE-2,i+1,j) ) ) &
           / ( f2h1_UYZ_KEm2 * 0.5_RP * ( DENS(KE-1,i,j)+DENS(KE-1,i+1,j) ) &
             + f2h2_UYZ_KEm2 * 0.5_RP * ( DENS(KE-2,i,j)+DENS(KE-2,i+1,j) ) )
       flux(KE-2,i,j) = J33G * vel &
                   * ( F41 * ( val(KE-1,i,j)+val(KE-2,i,j) ) &
                     + F42 * ( val(KE,i,j)+val(KE-3,i,j) ) ) &
                   + GSQRT(KE-2,i,j) * num_diff(KE-2,i,j)

       f2h1_UYZ_KSp2 = F2H(KS+2,I_UYZ)
       f2h2_UYZ_KSp2 = 1.0_RP - f2h1_UYZ_KSp2
       vel = ( 0.5_RP * ( mom(KS+2,i,j)+mom(KS+2,i+1,j) ) ) &
           / ( f2h1_UYZ_KSp2 * 0.5_RP * ( DENS(KS+3,i,j)+DENS(KS+3,i+1,j) ) &
             + f2h2_UYZ_KSp2 * 0.5_RP * ( DENS(KS+2,i,j)+DENS(KS+2,i+1,j) ) )
       flux(KS+2,i,j) = J33G * vel &
                   * ( F61 * ( val(KS+3,i,j)+val(KS+2,i,j) ) &
                     + F62 * ( val(KS+4,i,j)+val(KS+1,i,j) ) &
                     + F63 * ( val(KS+5,i,j)+val(KS,i,j) ) ) &
                   + GSQRT(KS+2,i,j) * num_diff(KS+2,i,j)
       f2h1_UYZ_KEm3 = F2H(KE-3,I_UYZ)
       f2h2_UYZ_KEm3 = 1.0_RP - f2h1_UYZ_KEm3
       vel = ( 0.5_RP * ( mom(KE-3,i,j)+mom(KE-3,i+1,j) ) ) &
           / ( f2h1_UYZ_KEm3 * 0.5_RP * ( DENS(KE-2,i,j)+DENS(KE-2,i+1,j) ) &
             + f2h2_UYZ_KEm3 * 0.5_RP * ( DENS(KE-3,i,j)+DENS(KE-3,i+1,j) ) )
       flux(KE-3,i,j) = J33G * vel &
                   * ( F61 * ( val(KE-2,i,j)+val(KE-3,i,j) ) &
                     + F62 * ( val(KE-1,i,j)+val(KE-4,i,j) ) &
                     + F63 * ( val(KE,i,j)+val(KE-5,i,j) ) ) &
                   + GSQRT(KE-3,i,j) * num_diff(KE-3,i,j)

       flux(KE,i,j) = 0.0_RP
    enddo
    enddo
    !$acc end kernels
    !$omp end do nowait

    end if


    !$acc end data

    !$omp end parallel
#ifdef DEBUG
    k = IUNDEF; i = IUNDEF; j = IUNDEF
#endif

    return
