                   * ( F41 * ( val(KE-1,i,j)+val(KE-2,i,j) ) &
                     + F42 * ( val(KE,i,j)+val(KE-3,i,j) ) ) &
                   + GSQRT(KE-1,i,j) * num_diff(KE-1,i,j) ! k = KE-1

       flux(KE-1,i,j) = 0.0_RP ! k = KE
       flux(KE  ,i,j) = 0.0_RP ! k = KE+1
