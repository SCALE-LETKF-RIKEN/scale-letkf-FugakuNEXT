       call CHECK( __LINE__, val(k,i+2,j) )

       call CHECK( __LINE__, val(k,i-4,j) )
       call CHECK( __LINE__, val(k,i+3,j) )

#endif
       vel = ( 0.5_RP * ( mom(k,i,j)+mom(k,i-1,j) ) ) &
           / ( DENS(k,i,j) )
       flux(k,i-1,j) = GSQRT(k,i,j) / MAPF(i,j,+2) * vel &
